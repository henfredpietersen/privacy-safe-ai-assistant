  function render(t, note) {
    var steps = t.steps || [];
    var find = function (k) { return steps.filter(function (s) { return s.kind === k; })[0]; };
    var red = find("redact"), model = find("model"), tool = find("tool"), guard = find("guard");
    var rows = [];
    if (red) {
      rows.push(item("pass", "✓", "Personal details removed",
        esc(red.emails) + " email(s), " + esc(red.ids) + " ID number(s). The rest of the run only sees: <code>" + esc(red.after) + "</code>"));
    } else {
      rows.push(item("pass", "✓", "Personal details", "No email addresses or 13-digit ID numbers found."));
    }
    if (guard && guard.reason === "router_error") {
      rows.push(item("stop", "✕", "Model call failed, so the run stopped", "<code>" + esc(guard.error) + "</code>"));
    } else if (model) {
      rows.push(item("pass", "→", "Model proposed", "<code>" + esc(JSON.stringify(model.call)) + "</code> <span class='dimc'>(" + esc(model.router) + ")</span>"));
    }
    if (t.status === "no_tool") rows.push(item("stop", "✕", "No tool fits this request", "So it doesn't act."));
    if (guard && guard.reason === "unknown_tool") rows.push(item("stop", "✕", "Tool is not on the allowlist", "<code>" + esc(guard.tool) + "</code> doesn't exist. Blocked."));
    if (guard && guard.reason === "schema") rows.push(item("stop", "✕", "Arguments don't match the tool's schema", "<code>" + esc(guard.detail) + "</code>. Blocked."));
    if (tool) {
      var r = tool.result || {};
      var det = r.doc_id ? "Best match <code>" + esc(r.doc_id) + "</code>, score <b>" + esc(r.score) + "</b>" :
        "Found " + esc(r.count) + " customer(s)";
      rows.push(item("pass", "✓", "Tool ran: " + tool.tool, det));
    } else if (t.status !== "ok") {
      rows.push(item("skip", "–", "No tool ran", ""));
    }
    if (guard && guard.reason === "low_score") rows.push(item("stop", "✕", "Score " + guard.score + " is below 0.15", "So it declines instead of guessing."));
    else if (tool && tool.result && tool.result.doc_id) rows.push(item("pass", "✓", "Score is at least 0.15", "Confident enough to answer."));
    var st = STATUS[t.status] || ["dimc", t.status];
    $("#result").innerHTML =
      "<div class='row' style='margin-bottom:10px'><span class='pill " + st[0] + "'>" + esc(st[1]) + "</span><span class='dimc' style='font-size:.8rem'>run " + esc(t.run_id) + "</span></div>" +
      "<p class='final'>" + esc(t.output) + "</p>" +
      (note ? "<div class='callout'><b style='color:#fde68a'>Known failure.</b> " + esc(note) + "</div>" : "") +
      "<ol class='guards'>" + rows.join("") + "</ol>" +
      "<details><summary>Show the saved trace (JSON)</summary><pre>" + esc(JSON.stringify(t, null, 2)) + "</pre></details>";
    $("#result").hidden = false;
  }

  var py = null, busy = false;
  function run(message, kase, note) {
    if (!py || busy) return;
    busy = true;
    try {
      py.globals.set("_msg", message);
      py.globals.set("_case", kase || "");
      var out = py.runPython("import demo_driver\ndemo_driver.demo(_msg, _case or None)");
      render(JSON.parse(out), note);
      $("#result").scrollIntoView({ behavior: "smooth", block: "nearest" });
    } catch (e) {
      $("#result").innerHTML = "<p class='bad' style='margin:0'>Something went wrong running the agent: " + esc(e && e.message) + "</p>";
      $("#result").hidden = false;
    }
    busy = false;
  }

